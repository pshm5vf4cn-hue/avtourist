  function renderResult() {
    resultRoot.innerHTML = "";
    if (!state.topic) {
      resultRoot.appendChild(el("p", "op-result-empty", "Отвечайте на шаги слева — здесь появятся заключение для клиента, категория заявки, скрипт записи и карточка для CRM."));
      return;
    }
    var topic = TOPICS[state.topic];

    if (state.readiness) {
      var r = READINESS[state.readiness];
      var cat = el("span", "op-cat " + r.cat, r.catName);
      resultRoot.appendChild(cat);
      var act = el("p", null, r.action);
      act.style.marginBottom = "18px";
      resultRoot.appendChild(act);
    }

    var say = topic.say;
    if (state.timing) say += "\n\n" + TIMINGS[state.timing].note;
    if (state.docs.indexOf("Пока ничего нет") !== -1) {
      say += "\n\nДокументов пока нет — успокойте: «Ничего страшного, юрист подскажет, что восстановить и как. Начнём с вашего рассказа».";
    } else if (state.docs.length) {
      say += "\n\nДокументы есть — подчеркните: «Разбор будет предметным и быстрым, держите их под рукой».";
    }
    resultRoot.appendChild(sayBlock("Заключение для клиента (что говорить)", say, true));

    if (state.readiness) {
      resultRoot.appendChild(sayBlock("Добивка на запись / следующий шаг", READINESS[state.readiness].close, true));
    } else {
      resultRoot.appendChild(el("p", "op-hint", "Выберите готовность клиента на шаге 5 — появится скрипт записи и категория."));
    }

    if (state.timing === "old") {
      resultRoot.appendChild(el("div", "op-warn", TIMINGS.old.warn));
    }

    var crm = "Тема: " + topic.crm +
      "\nРоль: " + (state.role || "не указана") +
      "\nДавность ДТП: " + (state.timing ? TIMINGS[state.timing].label : "не указана") +
      "\nДокументы: " + (state.docs.length ? state.docs.join(", ") : "не указано") +
      "\nРекомендуемые документы: " + topic.docs +
      "\nКатегория: " + (state.readiness ? READINESS[state.readiness].catName : "не выбрана");
    resultRoot.appendChild(sayBlock("Карточка для юриста в CRM", crm, true));
  }
