  var nextBtn = document.getElementById("slideNext");
  var slideIdx = 0;
  function renderSlide() {
    var s = SLIDES[slideIdx];
    slideCard.innerHTML = "";
    slideCard.appendChild(el("div", "op-slide-num", "Слайд " + (slideIdx + 1) + " / " + SLIDES.length));
    slideCard.appendChild(el("h2", null, s.title));
    var ul = el("ul");
    s.bullets.forEach(function (b) { ul.appendChild(el("li", null, b)); });
    slideCard.appendChild(ul);
    prevBtn.disabled = slideIdx === 0;
    nextBtn.textContent = slideIdx === SLIDES.length - 1 ? "В начало" : "Дальше →";
  }
  prevBtn.addEventListener("click", function () { if (slideIdx > 0) { slideIdx--; renderSlide(); } });
  nextBtn.addEventListener("click", function () { slideIdx = (slideIdx + 1) % SLIDES.length; renderSlide(); });
  document.addEventListener("keydown", function (e) {
    if (document.querySelector('[data-panel="training"]').hidden) return;
    if (e.key === "ArrowRight") nextBtn.click();
    if (e.key === "ArrowLeft") prevBtn.click();
  });
