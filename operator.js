  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function copyText(text, btn) {
    function done() {
      var old = btn.textContent;
      btn.textContent = "Скопировано ✓";
      btn.classList.add("ok");
      setTimeout(function () { btn.textContent = old; btn.classList.remove("ok"); }, 1600);
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(done, function () { fallback(); });
    } else fallback();
    function fallback() {
      var ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      try { document.execCommand("copy"); } catch (e) {}
      document.body.removeChild(ta);
      done();
    }
  }
  function copyBtn(getText) {
    var b = el("button", "op-copy", "Копировать");
    b.type = "button";
    b.addEventListener("click", function () { copyText(getText(), b); });
    return b;
  }
  function sayBlock(title, text, withCopy) {
    var wrap = el("div", "op-block");
    wrap.appendChild(el("h4", null, title));
    wrap.appendChild(el("div", "op-say", text));
    if (withCopy) wrap.appendChild(copyBtn(function () { return text; }));
    return wrap;
  }

